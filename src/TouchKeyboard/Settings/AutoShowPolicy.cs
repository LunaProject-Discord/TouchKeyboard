namespace TouchKeyboard.Settings;

/// <summary>
/// アプリごとの自動表示の扱い。
///
/// 入力欄にフォーカスが移る理由はアプリによって違う。利用者が押したから移ることも、
/// アプリが開いた勢いで自分から移すこともある。後者まで拾うと意図せず出てしまうため、
/// アプリ単位で強さを選べるようにする。
/// </summary>
public enum AutoShowPolicy
{
    /// <summary>フォーカスが当たったら表示する。既定。</summary>
    Auto = 0,

    /// <summary>
    /// 自動表示はするが、利用者が自分でフォーカスを当てた場合のみ。
    ///
    /// アプリが自分からフォーカスを移した場合は出さない。スタートメニューのように
    /// 開いただけで検索ボックスへフォーカスが移るものに使う。
    /// 判別はタッチとフォーカスの前後関係による。
    /// </summary>
    Strict = 1,

    /// <summary>自動では表示しない。トレイからの手動表示のみ。</summary>
    Suppress = 2,
}
